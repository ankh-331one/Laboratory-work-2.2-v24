#include <stdio.h>
#include <locale.h>
#include <malloc.h>
#include <math.h>

int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("-------------------------------------------------------------------\n");

    int n;
    do {
        printf("\nВведите количество элементов массива n: ");
        scanf("%d", &n);
        if (n <= 0 || n >= 100){
            printf("\n===================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n===================================================================\n");
        }
    }while (n <= 0 || n >= 100);

    printf("\n-------------------------------------------------------------------\n");

    double *x;
    x = (double*) malloc(n*sizeof(double));

    printf("\nВведите элементы массива X: \n");
    for (int i = 0; i < n; i++){
        printf("\nX[%d]: ",i);
        scanf("%lf", &x[i]);
    }

    printf("\n-------------------------------------------------------------------\n");

    printf("\nВведено количество элементов n: %d\n", n);
    printf("\nВведeнo массив: [ %g", x[0]);
    for (int i = 1; i < n; i++){
        printf("; %g", x[i]);
    }
    printf(" ]\n");

    double k = 0, b = 0, tg;
    for (int i = 0; i < n; i++){
        tg = tan(3.14*x[i]/180);
        if (tg > 0){
            k += tg;
            b ++;
        }
    }

    printf("\n===================================================================\n\n\t\t\t");

    printf("Результат: ");
    if (k != 0 && b != 0){
        printf("%.3f", k/b);
    }else
        printf("\nнет подходящих элементов");

    printf("\n\n===================================================================\n");

    free(x);

    return 0;
}
