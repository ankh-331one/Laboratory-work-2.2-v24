/**
Разработать программу вычисления требуемой величины на основе
заданного одномерного массива. Имейте в виду, что в некоторых задачах
возможны несколько вариантов ответов.

24. В заданном массиве X1, X2, ..., Xn заменить значения отрицательных
элементов их абсолютными величинами, при этом подсчитать число
элементов, равных нулю.
*/
#include <stdio.h>
#include <locale.h>
#include <malloc.h>

int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("-------------------------------------------------------------------\n");

    int n, k = 0;
    do {
        printf("\nВведите количество элементов массива n: ");
        scanf("%d", &n);
        if (n <= 0 || n >= 100){
            printf("\n===================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных");
            printf("\n===================================================================\n");
        }
    }while (n <= 0 || n >= 100);

    printf("\n-------------------------------------------------------------------\n");

    double *x;
    x = (double*) malloc(n*sizeof(double));

    printf("\nВведите элементы массива X: \n");
    for (int i = 0; i < n; i++){
        printf("\nX[%d]: ",i);
        scanf("%lf", &x[i]);
    }

    printf("\n-------------------------------------------------------------------\n");

    printf("\nВведено количество элементов n: %d\n", n);
    printf("\nВведeнo массив: [ %g", x[0]);
    for (int i = 1; i < n; i++){
        printf("; %g", x[i]);
    }
    printf(" ]\n");

    for (int i = 0; i < n; i++){
        if (x[i] == 0){
            k += 1;
        }else if (x[i] < 0){
            x[i] *= (-1);
        }
    }

    printf("\n===================================================================\n\n\t\t\t");

    printf("Результат\n\n");

    printf("Преобразованный массив X: [ %g", x[0]);
    for (int i = 1; i < n; i++){
        printf("; %g", x[i]);
    }
    printf(" ]\n\n");

    printf("Количество нулевых элементов: %d", k);

    printf("\n\n===================================================================\n");

    free(x);

    return 0;
}
